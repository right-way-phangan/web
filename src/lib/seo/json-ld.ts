/**
 * Безопасная сериализация данных для <script type="application/ld+json">.
 *
 * JSON.stringify НЕ экранирует последовательность "</script>". Если в данные
 * структуры (название объекта из amoCRM, заголовок статьи блога) попадёт
 * "</script>", вывод выходит из <script> и даёт XSS — причём CSP здесь не
 * спасает, потому что script-src разрешает 'unsafe-inline'.
 *
 * Экранируем '<' (этого достаточно: без него нельзя сформировать ни закрытие,
 * ни открытие тега); '>' и '&' экранируем за компанию, чтобы результат не
 * зависел от тонкостей HTML-парсера. Содержимое ld+json парсится как JSON,
 * поэтому \uXXXX-последовательности остаются валидными.
 */
export function jsonLdHtml(data: unknown): string {
  return JSON.stringify(data)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026");
}

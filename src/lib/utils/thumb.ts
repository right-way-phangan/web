/**
 * Лёгкое webp-превью рядом с исходным фото лота для каруселей/коллажа (полные
 * фото остаются в лайтбоксе). Превью предгенерятся скриптом sharp:
 *   r7-1.jpg → r7-1-sm.webp  (width 760, q68 — ~⅓ от исходного JPG).
 * Если файла нет, ссылка будет битой — поэтому генерируем для ВСЕХ фото папки.
 */
export function estateThumb(src: string): string {
  return src.replace(/\.(jpe?g|png)$/i, "-sm.webp");
}

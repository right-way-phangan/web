import { describe, expect, it } from "vitest";
import { parseBlocks } from "./blocks";

/**
 * Регрессия 2026-07-28: страница справочника с `# H1` в теле не открывалась
 * вообще — не 404 и не 500, а вечное молчание сервера. Заголовки ловились
 * регуляркой `#{2,6}`, одиночная решётка не подходила ни одному блоку, а ветка
 * параграфа обрывалась на `startsWith("#")`, не сдвинув счётчик строк: внешний
 * цикл брал ту же строку снова и снова. В браузере это выглядело как «ссылка
 * не нажимается». Тест на зацикливание работает по таймауту: до фикса он бы
 * не завершился.
 */
describe("parseBlocks", () => {
  it("разбирает H1 как заголовок, а не уходит в цикл", () => {
    const blocks = parseBlocks("# Заголовок страницы\n\nтекст под ним");
    expect(blocks[0]).toEqual({ kind: "h2", text: "Заголовок страницы" });
    expect(blocks[1]).toEqual({ kind: "p", text: "текст под ним" });
  });

  it("не зависает на строке, которая не подходит ни одному блоку", () => {
    // «#» без текста не заголовок (нужен пробел и содержимое) и не параграф —
    // ровно тот случай, где счётчик раньше не двигался.
    const blocks = parseBlocks("#\n\nдальше текст");
    expect(blocks.at(-1)).toEqual({ kind: "p", text: "дальше текст" });
  });

  it("не ломает обычную разметку справочника", () => {
    const md = [
      "## Раздел",
      "",
      "Обычный параграф.",
      "",
      "- пункт один",
      "- пункт два",
      "",
      "### Подраздел",
      "",
      "> колл-аут",
    ].join("\n");
    expect(parseBlocks(md).map((b) => b.kind)).toEqual(["h2", "p", "ul", "h3", "quote"]);
  });
});
